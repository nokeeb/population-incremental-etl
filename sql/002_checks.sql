-- Double area code in target
SELECT
	AREA_CODE,
	COUNT(*) AS COUNT_AREA_CODE
FROM
	ANALYTICS.AREA_POPULATION
GROUP BY
	AREA_CODE
HAVING
	COUNT(*) > 1;

-- NULL columns / empty area_code or area_name
SELECT
	AREA_CODE,
	AREA_NAME,
	POPULATION,
	REFERENCE_YEAR,
	SOURCE_UPDATED_AT,
	LOADED_AT,
	LAST_RUN_ID
FROM
	ANALYTICS.AREA_POPULATION
WHERE
	(
		AREA_CODE IS NULL
		OR AREA_NAME IS NULL
		OR POPULATION IS NULL
		OR REFERENCE_YEAR IS NULL
		OR SOURCE_UPDATED_AT IS NULL
		OR LOADED_AT IS NULL
		OR LAST_RUN_ID IS NULL
	)
	OR 
		BTRIM(AREA_CODE) = ''
		OR BTRIM(AREA_NAME) = ''
	;

-- Negative population
SELECT
	POPULATION,
	AREA_CODE
FROM
	ANALYTICS.AREA_POPULATION
WHERE
	POPULATION < 0;

-- Target rows with newer source_updated_at than the last watermark
SELECT
	TARGET.AREA_CODE,
	TARGET.SOURCE_UPDATED_AT,
	PIPELINE.LAST_WATERMARK
FROM
	ANALYTICS.AREA_POPULATION AS TARGET
	CROSS JOIN ETL.PIPELINE_STATE AS PIPELINE
WHERE
	TARGET.SOURCE_UPDATED_AT > PIPELINE.LAST_WATERMARK;

-- Successful audit runs with valid_count different from total(inserted+unchanged+updated)
SELECT
	RUN_ID,
	VALID_COUNT,
	(INSERTED_COUNT + UPDATED_COUNT + UNCHANGED_COUNT) AS TOTAL_COUNT,
	STATUS
FROM
	ETL.PIPELINE_RUNS
WHERE
	VALID_COUNT <> (INSERTED_COUNT + UPDATED_COUNT + UNCHANGED_COUNT)
	AND STATUS = 'SUCCESS';

