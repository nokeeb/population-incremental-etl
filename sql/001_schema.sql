CREATE SCHEMA IF NOT EXISTS SOURCE;

CREATE SCHEMA IF NOT EXISTS STAGING;

CREATE SCHEMA IF NOT EXISTS ANALYTICS;

CREATE SCHEMA IF NOT EXISTS ETL;

CREATE TABLE IF NOT EXISTS SOURCE.AREA_POPULATION (
	AREA_CODE TEXT PRIMARY KEY,
	AREA_NAME TEXT,
	POPULATION_RAW TEXT,
	REFERENCE_YEAR INTEGER,
	UPDATED_AT TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS ETL.PIPELINE_RUNS (
	RUN_ID UUID PRIMARY KEY,
	STARTED_AT TIMESTAMPTZ NOT NULL,
	FINISHED_AT TIMESTAMPTZ,
	STATUS TEXT NOT NULL,
	WATERMARK_BEFORE TIMESTAMPTZ,
	WATERMARK_AFTER TIMESTAMPTZ,
	EXTRACTED_COUNT INTEGER DEFAULT 0 NOT NULL,
	VALID_COUNT INTEGER DEFAULT 0 NOT NULL,
	INVALID_COUNT INTEGER DEFAULT 0 NOT NULL,
	INSERTED_COUNT INTEGER DEFAULT 0 NOT NULL,
	UPDATED_COUNT INTEGER DEFAULT 0 NOT NULL,
	UNCHANGED_COUNT INTEGER DEFAULT 0 NOT NULL,
	ERROR_MESSAGE TEXT,
	CHECK (
		STATUS LIKE 'RUNNING'
		OR STATUS LIKE 'SUCCESS'
		OR STATUS LIKE 'FAILED'
	),
	CHECK (EXTRACTED_COUNT >= 0),
	CHECK (VALID_COUNT >= 0),
	CHECK (INVALID_COUNT >= 0),
	CHECK (INSERTED_COUNT >= 0),
	CHECK (UPDATED_COUNT >= 0),
	CHECK (UNCHANGED_COUNT >= 0)
);

CREATE TABLE IF NOT EXISTS ETL.PIPELINE_STATE (
	PIPELINE_NAME TEXT PRIMARY KEY,
	LAST_WATERMARK TIMESTAMPTZ
);

INSERT INTO
	ETL.PIPELINE_STATE (PIPELINE_NAME, LAST_WATERMARK)
VALUES
	('area_population', NULL)
ON CONFLICT DO NOTHING;

CREATE TABLE IF NOT EXISTS ANALYTICS.AREA_POPULATION (
	AREA_CODE TEXT PRIMARY KEY,
	AREA_NAME TEXT NOT NULL,
	POPULATION BIGINT NOT NULL,
	REFERENCE_YEAR INTEGER NOT NULL,
	SOURCE_UPDATED_AT TIMESTAMPTZ NOT NULL,
	LOADED_AT TIMESTAMPTZ NOT NULL,
	LAST_RUN_ID UUID NOT NULL REFERENCES ETL.PIPELINE_RUNS,
	CHECK (BTRIM(AREA_NAME) <> ''),
	CHECK (POPULATION >= 0),
	CHECK (REFERENCE_YEAR = 2014),
	CHECK (AREA_CODE ~ '^[A-Z]{2}$')
);

CREATE TABLE IF NOT EXISTS STAGING.AREA_POPULATION (
	RUN_ID UUID NOT NULL,
	AREA_CODE TEXT NOT NULL,
	AREA_NAME TEXT NOT NULL,
	POPULATION BIGINT NOT NULL,
	REFERENCE_YEAR INTEGER NOT NULL,
	SOURCE_UPDATED_AT TIMESTAMPTZ NOT NULL,
	PRIMARY KEY (RUN_ID, AREA_CODE)
);